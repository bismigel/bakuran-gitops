#!/usr/bin/env bash
# Snapshot the live ArgoCD runtime objects into install/argocd/runtime.yaml.
#
# Why this exists: the `argocd-runtime` Application runs with prune:false and
# selfHeal:true, so it can only own what is written in runtime.yaml. An empty
# runtime.yaml makes the Application report Synced while managing nothing —
# which is the current state. This script exports the workloads and Services
# that actually run, so the file reflects reality instead of a guess.
#
# It never applies anything. It reads the cluster and writes one file.
#
# Usage: ./scripts/snapshot-argocd-runtime.sh [outfile]
set -euo pipefail

NS="${NS:-argocd}"
OUT="${1:-install/argocd/runtime.yaml}"

command -v kubectl >/dev/null || { echo "kubectl is required" >&2; exit 1; }
command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }

echo "Exporting Deployments, StatefulSets and Services from namespace ${NS}..."

{
  echo "# Generated by scripts/snapshot-argocd-runtime.sh — do not hand-edit."
  echo "# Snapshot of the live ArgoCD workloads, reconciled by the argocd-runtime"
  echo "# Application with prune:false + selfHeal:true. Server-populated fields"
  echo "# (status, uid, resourceVersion, managedFields) are stripped; everything"
  echo "# else is the state that is actually running."
  kubectl -n "$NS" get deploy,sts,svc -o json | jq -r '
    .items[]
    | .metadata.managedFields = null
    | .metadata.annotations = ((.metadata.annotations // {})
        | del(.["kubectl.kubernetes.io/last-applied-configuration"],
              .["deployment.kubernetes.io/revision"]))
    | del(.status,
          .metadata.uid,
          .metadata.resourceVersion,
          .metadata.creationTimestamp,
          .metadata.generation,
          .metadata.selfLink)
    | "---\n" + tojson
  '
} > "$OUT"

echo "Wrote $(grep -c '^---$' "$OUT") objects to ${OUT}"
echo
echo "Review the diff before committing. Cluster-assigned defaults (clusterIP,"
echo "nodePort, strategy, resourceVersion-free spec defaults) are captured on"
echo "purpose: this is the state you actually run, not a minimal manifest."
